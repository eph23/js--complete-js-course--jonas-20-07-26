"use strict";

// ANCHOR: The for loop
/* NOTE: 
A JavaScript for loop repeats a block of code a specific number of times based on three optional expressions enclosed in parentheses. It is an entry-controlled loop, meaning it checks the condition before executing any code inside its block.
*/

for (let rep = 1; rep <= 5; rep++) {
    console.log(`Lifting weights repetition ${rep}`);
}
